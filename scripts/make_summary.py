#!/usr/bin/env python3
"""Write reports/summary.md from the final hardening run, the TT precheck, the
RTL and gate-level test results and reports/sweep.md."""
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import metrics  # noqa: E402


def junit(path):
    """[(module, test, PASS/FAIL/SKIP, sim time ns, wall time s)] from a cocotb results.xml."""
    if not os.path.exists(path):
        return None
    tests = []
    for tc in ET.parse(path).getroot().iter("testcase"):
        failed = tc.find("failure") is not None or tc.find("error") is not None
        skipped = tc.find("skipped") is not None
        props = {p.get("name"): p.get("value") for p in tc.iter("property")}
        sim_ns = float(props.get("sim_time_duration", tc.get("sim_time_ns", 0)) or 0)
        tests.append((tc.get("classname", ""), tc.get("name"), "SKIP" if skipped else ("FAIL" if failed else "PASS"),
                      sim_ns, float(tc.get("time", 0) or 0)))
    return tests


def corner(m, key, c):
    return m.get(f"{key}__corner:{c}")


def precheck():
    """(passed?, klayout item counts, magic count) from logs/precheck.log and reports/precheck/."""
    log = os.path.join(ROOT, "logs", "precheck.log")
    if not os.path.exists(log):
        return None
    passed = "Precheck passed" in open(log, errors="replace").read()
    rep = os.path.join(ROOT, "reports", "precheck")
    kl = {}
    magic = None
    if os.path.isdir(rep):
        for fn in sorted(os.listdir(rep)):
            p = os.path.join(rep, fn)
            if fn.startswith("drc_") and fn.endswith(".xml"):
                kl[fn[4:-4]] = open(p).read().count("<item>")
            if fn == "magic_drc.txt":
                mm = re.search(r"COUNT:\s*(\d+)", open(p).read())
                magic = int(mm.group(1)) if mm else None
    return passed, kl, magic


def first_table(path):
    """Lines of the first markdown table in a file."""
    rows, started = [], False
    for line in open(path).read().splitlines():
        if line.startswith("|"):
            rows.append(line)
            started = True
        elif started:
            break
    return rows


def main():
    run = os.path.join(ROOT, "runs", "wokwi")
    s = metrics.summarise(run)
    m = metrics.load_metrics(run)
    info = open(os.path.join(ROOT, "info.yaml")).read()
    clock_hz = int(re.search(r"clock_hz:\s*(\d+)", info).group(1))
    top = re.search(r'top_module:\s*"([^"]+)"', info).group(1)
    rtl = junit(os.path.join(ROOT, "logs", "rtl_results.xml"))
    gl = junit(os.path.join(ROOT, "logs", "gl_results.xml"))
    fpga_log = os.path.join(ROOT, "fpga", "build", "sim.log")
    fpga_ok = os.path.exists(fpga_log) and "[tb_fpga] PASS" in open(fpga_log).read()
    pc = precheck()

    f = metrics.fmt
    L = []
    L.append(f"# Summary: {top}\n")
    L.append("Tiny Tapeout SKY 26d, sky130A, LibreLane " + os.environ.get("LIBRELANE_TAG", "3.0.14") +
             ". Generated by `scripts/make_summary.py` from `runs/wokwi/final/metrics.json`, "
             "`logs/precheck.log`, `logs/rtl_results.xml` and `logs/gl_results.xml`.\n")
    L.append("![Final layout](../docs/images/layout.png)\n")
    L.append("## Physical\n")
    L.append("| Item | Value |\n|---|---|")
    L.append(f"| Tile size | {s['tiles']} |")
    L.append(f"| Clock | {clock_hz/1e6:.0f} MHz (CLOCK_PERIOD {s['clock_period_ns']} ns) |")
    L.append(f"| Placement density target | {s['pl_target_density_pct']} % |")
    L.append(f"| Std-cell instances | {f(s['stdcell_instances'] or s['instances'])} |")
    L.append(f"| Std-cell area | {f(s['cell_area_um2'], 0)} um2 (core {f(s['core_area_um2'], 0)} um2) |")
    util = s["utilization"]
    L.append(f"| Utilisation | {util*100:.1f} % |" if isinstance(util, (int, float)) else "| Utilisation | - |")
    L.append(f"| Routed wire length | {f(s['wirelength_um'], 0)} um |")
    for c in ("nom_tt_025C_1v80", "min_tt_025C_1v80", "max_tt_025C_1v80", "nom_ff_n40C_1v95", "nom_ss_100C_1v60"):
        L.append(f"| Setup WNS / TNS @ {c} | {f(corner(m, 'timing__setup__ws', c))} / {f(corner(m, 'timing__setup__tns', c))} ns |")
    L.append(f"| Hold WNS / TNS, worst of all 9 corners | {f(s['hold_ws_ns'])} / {f(s['hold_tns_ns'])} ns |")
    L.append(f"| Hold violations (all corners) | {f(s['hold_violations'])} |")
    kl = "-"
    if pc and pc[1]:
        kl = str(sum(pc[1].values())) + " (TT precheck)"
    L.append(f"| Magic DRC / KLayout DRC / route DRC | {f(s['magic_drc_errors'])} / {kl} / {f(s['route_drc_errors'])} |")
    L.append(f"| LVS errors | {f(s['lvs_errors'])} |")
    L.append(f"| Antenna violating nets / pins | {f(s['antenna_violating_nets'])} / {f(s['antenna_violating_pins'])} |")
    L.append(f"| Max slew violations @ nom_tt / all corners (informational) | "
             f"{f(corner(m, 'design__max_slew_violation__count', 'nom_tt_025C_1v80'))} / {f(s['max_slew_violations'])} |")
    L.append(f"| Max cap violations @ nom_tt / all corners (informational) | "
             f"{f(corner(m, 'design__max_cap_violation__count', 'nom_tt_025C_1v80'))} / {f(s['max_cap_violations'])} |")
    pw = m.get("power__total")
    if isinstance(pw, (int, float)):
        L.append(f"| Power (STA estimate, tt) | {pw*1000:.1f} mW |")
    L.append("")
    L.append("The flow enforces setup at the typical corners (`TIMING_VIOLATION_CORNERS = *tt*`) "
             "and hold at all corners; slew and capacitance are reported, not enforced. Slow-corner "
             "(ss, 100 C, 1.60 V) setup slack is for information. See `reports/sweep.md` and "
             "`docs/DESIGN_REPORT.md` section 8.5 for the explanation of the slew warnings.\n")

    L.append("## Tiny Tapeout precheck\n")
    if pc is None:
        L.append("not run (`scripts/precheck.sh`)\n")
    else:
        L.append(("**PASSED**" if pc[0] else "**FAILED**") + " (`scripts/precheck.sh`, log `logs/precheck.log`, "
                 "reports `reports/precheck/`)\n")
        L.append("| Check | Errors |\n|---|---|")
        L.append(f"| Magic DRC | {f(pc[2])} |")
        for k, v in pc[1].items():
            L.append(f"| KLayout {k} | {v} |")
        L.append("| top cell, layers, prBoundary, pins, Verilog | " + ("pass" if pc[0] else "see log") + " |")
        L.append("")

    for title, res in (("RTL simulation", rtl), ("Gate-level simulation", gl)):
        L.append(f"## {title}\n")
        if res is None:
            L.append("not run\n")
            continue
        npass = sum(1 for t in res if t[2] == "PASS")
        wall = sum(t[4] for t in res)
        L.append(f"{npass}/{len(res)} passed (wall time {wall/60:.0f} min).\n")
        L.append("| Test | Result | Simulated time (ms) | Wall time (s) |\n|---|---|---|---|")
        for cls, name, r, t, w in res:
            L.append(f"| {cls}.{name} | {r} | {t/1e6:.3f} | {w:.0f} |")
        L.append("")
    L.append("## FPGA (PYNQ-Z2, xc7z020)\n")
    L.append(("PASS" if fpga_ok else "not run / FAIL") + ": Icarus simulation of the harness (`make -C fpga sim`).\n")
    vs = os.path.join(ROOT, "reports", "fpga", "vivado_summary.txt")
    if os.path.exists(vs):
        L.append("Vivado 2025.1 flow (`fpga/pynq_z2/build_on_windows.ps1`: xsim RTL simulations, "
                 "synthesis, implementation, bitstream, xsim on the post-route netlist), from "
                 "`reports/fpga/vivado_summary.txt` (reports and logs in `reports/fpga/`):\n")
        L.append("```")
        L.extend(line.rstrip() for line in open(vs, errors="replace") if line.strip())
        L.append("```\n")
    L.append("Board test: deferred until the board is available.\n")
    sweep = os.path.join(ROOT, "reports", "sweep.md")
    if os.path.exists(sweep):
        L.append("## Hardening iterations\n")
        L.extend(first_table(sweep))
        L.append("")
    out = os.path.join(ROOT, "reports", "summary.md")
    open(out, "w").write("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
